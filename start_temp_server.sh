#!/usr/bin/env bash
# ==============================================================================
# Скрипт быстрого запуска изолированного тестового сервера Resonance
# Максимальное число одновременных пользователей: 5
# Автоматическая остановка и чистка после завершения теста
# ==============================================================================

set -e

PORT=3000
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$SCRIPT_DIR"

echo "==================================================================="
echo "   ЗАПУСК ИЗОЛИРОВАННОГО ТЕСТОВОГО СЕРВЕРА (ЛИМИТ: 5 ЧЕЛОВЕК)"
echo "==================================================================="

# Определение локального IP-адреса для тестирования по Wi-Fi / LAN
LOCAL_IP=$(hostname -I 2>/dev/null | awk '{print $1}' || echo "127.0.0.1")

echo "1. Локальный доступ на этом ПК:   http://localhost:${PORT}"
echo "2. Доступ для других (по Wi-Fi): http://${LOCAL_IP}:${PORT}"
echo "-------------------------------------------------------------------"
echo "Ограничение нагрузки: МАКСИМУМ 5 ОДНОВРЕМЕННЫХ ПОЛЬЗОВАТЕЛЕЙ"
echo "Для остановки сервера и очистки нажмите: Ctrl + C"
echo "==================================================================="
echo ""

# Проверяем, есть ли Docker
if command -v docker &> /dev/null && docker info &> /dev/null; then
    echo "-> Обнаружен Docker. Запуск изолированного контейнера Nginx (256MB RAM)..."
    cd temp_server
    docker compose up --build --force-recreate
else
    echo "-> Docker не найден. Запуск изолированного легковесного сервера Python..."
    python3 serve_limited.py ${PORT}
fi
